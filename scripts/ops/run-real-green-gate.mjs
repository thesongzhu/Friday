function resolveCurrentBranch(repoRoot) {
  const envBranch = process.env.GITHUB_HEAD_REF || process.env.GITHUB_REF_NAME;
  if (envBranch && envBranch.trim().length > 0) {
    return envBranch.trim();
  }
  return runCommandCapture(repoRoot, "git", ["symbolic-ref", "--quiet", "--short", "HEAD"]).stdout.trim() || "main";
}

function parseArgs(argv) {
  const options = {
    repoRoot: process.cwd(),
    mintLocalAdminToken: false,
    dailyCoreRepetitions: 1,
    liveProviderMode: normalizeLiveProviderMode(process.env.FRIDAY_REAL_GREEN_GATE_LIVE_PROVIDER_MODE),
    validationTimeoutMs: parseOptionalInteger(process.env.FRIDAY_REAL_GREEN_GATE_VALIDATION_TIMEOUT_MS) ?? 20 * 60 * 1000,
    skillTestTimeoutMs: parseOptionalInteger(process.env.FRIDAY_REAL_GREEN_GATE_SKILL_TIMEOUT_MS) ?? 5 * 60 * 1000,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const next = argv[index + 1];
    switch (arg) {
      case "--repo-root":
        options.repoRoot = path.resolve(next);
        index += 1;
        break;
      case "--base-url":
        options.baseUrl = next;
        index += 1;
        break;
      case "--ui-base-url":
        options.uiBaseUrl = next;
        index += 1;
        break;
      case "--branch":
        options.branch = next;
        index += 1;
        break;
      case "--report-root":
        options.reportRoot = path.resolve(next);
        index += 1;
        break;
      case "--daily-core-repetitions":
        options.dailyCoreRepetitions = Number.parseInt(next, 10) || 1;
        index += 1;
        break;
      case "--live-provider-mode":
        options.liveProviderMode = normalizeLiveProviderMode(next);
        index += 1;
        break;
      case "--validation-timeout-ms":
        options.validationTimeoutMs = parseOptionalInteger(next) ?? options.validationTimeoutMs;
        index += 1;
        break;
      case "--skill-test-timeout-ms":
        options.skillTestTimeoutMs = parseOptionalInteger(next) ?? options.skillTestTimeoutMs;
        index += 1;
        break;
      case "--mint-local-admin-token":
        options.mintLocalAdminToken = true;
        break;
      case "--skip-skill-tests":
        options.skipSkillTests = true;
        break;
      default:
        break;
    }
  }
  options.branch ??= resolveCurrentBranch(options.repoRoot);
  return options;
}

